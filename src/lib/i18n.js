/**
 * i18n — мінімальний мовний шар Morok Web.
 *
 * Джерело правди в коді — АНГЛІЙСЬКІ рядки: t('Chats').
 * Українська підставляється зі словника UA нижче.
 * Мова: localStorage 'morok.lang' -> навігатор (uk* => uk) -> en.
 * setLang() перезавантажує сторінку — найпростіший спосіб застосувати
 * мову скрізь без прокидання стану через 40 екранів.
 *
 * t(s)        — статичний рядок.
 * tp(key, a)  — рядок із підстановками: tp('{0}h {1}m', [h, m]).
 */

const LANG_KEY = 'morok.lang';

export function getLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'uk' || saved === 'en') return saved;
  } catch {}
  try {
    if ((navigator.language || '').toLowerCase().startsWith('uk')) return 'uk';
  } catch {}
  return 'en';
}

export function setLang(lang) {
  try { localStorage.setItem(LANG_KEY, lang); } catch {}
  location.reload();
}

const LANG = getLang();

export function t(s) {
  if (LANG !== 'uk') return s;
  return UA[s] ?? s;
}

export function tp(key, args) {
  let s = LANG === 'uk' ? (UA[key] ?? key) : key;
  for (let i = 0; i < args.length; i++) s = s.replaceAll('{' + i + '}', String(args[i]));
  return s;
}

